import time, sys

try:
    while True:
        #increase -- the length
        for i in range(1,9):
         print('-' * (i*i))
         time.sleep(0.1)

         #decrease -- the length
        for i in range(7,1, -1):
           print('-' * (i*i))
           time.sleep(0.1)
except KeyboardInterrupt:
   sys.exit()

        
           
